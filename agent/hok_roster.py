# 名字去重自检（同一个英雄不能出现两次）
_NAMES = [hero.character for hero in HEROES]
assert len(_NAMES) == len(set(_NAMES)), "王者角色池里有重复英雄"

_HOK_DECK = PersonaDeck(personas=tuple(HEROES))


def hero_names() -> List[str]:
    return [hero.character for hero in HEROES]


def deal_heroes(count: int) -> List[Persona]:
    """给一局发 count 个互不重复的英雄（含对应性格）。"""
    return _HOK_DECK.deal(count)
